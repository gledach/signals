// ─── Dashboard ───
function renderDashboard(cronRes) {
  const all = state.filtered;
  const critical = all.filter(s => s.impactBand === 'critical' || s.signalType === 'convergence');

  document.getElementById('stat-total').textContent = all.length;
  document.getElementById('stat-critical').textContent = critical.length;

  if (cronRes && cronRes.lastRun) {
    document.getElementById('stat-cron').textContent = timeAgo(cronRes.lastRun);
  } else {
    document.getElementById('stat-cron').textContent = '—';
  }

  const $list = document.getElementById('signal-list');
  const $heading = document.getElementById('signal-heading');
  const top = all.slice(0, 50);

  $heading.textContent = state.filtered.length < state.signals.length
    ? `Filtered signals (${state.filtered.length})`
    : 'Recent signals';

  if (top.length === 0) {
    $list.innerHTML = '<div class="loading">No signals match</div>';
    return;
  }

  $list.innerHTML = top.map((s, i) => {
    const band = s.impactBand || 'noise';
    const color = IMPACT_COLORS[band] || IMPACT_COLORS.noise;
    const company = state.companies.find(c => c.id === s.companyId);
    const companyName = company?.name || s.companyId;
    const summary = s.summary || '';
    return `
      <div class="signal-row" data-idx="${i}" style="--band-color: ${color}">
        <div class="signal-info">
          <div class="signal-title">${esc(s.title || summary.slice(0, 100) || '—')}</div>
          <div class="signal-meta">
            <span class="company">${esc(companyName)}</span> · ${esc(s.signalType || '')} · ${timeAgo(s.firstSeen)}
          </div>
          ${summary ? `<div class="signal-summary">${esc(summary)}</div>` : ''}
          <div class="tldr-slot" data-summary="${esc(summary)}"></div>
        </div>
        <span class="signal-badge band-${band}">${s.impactScore || '?'}</span>
        ${state.ai.summarizer !== 'unavailable' ? '<button class="btn-tldr" title="AI TL;DR">✨</button>' : ''}
      </div>`;
  }).join('');

  // Click → open signal detail
  $list.querySelectorAll('.signal-row').forEach(row => {
    row.addEventListener('click', (e) => {
      if (e.target.classList.contains('btn-tldr')) return;
      const idx = Number(row.dataset.idx);
      showSignalDetail(state.filtered[idx]);
    });
  });

  // TL;DR buttons
  $list.querySelectorAll('.btn-tldr').forEach(btn => {
    btn.addEventListener('click', async (e) => {
      e.stopPropagation();
      const row = btn.closest('.signal-row');
      const slot = row.querySelector('.tldr-slot');
      const summary = slot.dataset.summary;
      if (!summary || slot.querySelector('.tldr-result')) return;
      btn.textContent = '⏳';
      const result = await summarizeText(summary);
      if (result) {
        slot.innerHTML = `<div class="tldr-result">${esc(result)}</div>`;
      }
      btn.textContent = '✨';
    });
  });
}

