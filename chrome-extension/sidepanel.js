// ─── Submit clip to Turso (Step 2) ───
document.getElementById('btn-submit-clip').addEventListener('click', async () => {
  const $btn = document.getElementById('btn-submit-clip');
  const $status = document.getElementById('intel-clip-status');

  const companyId = document.getElementById('intel-company').value;

  const payload = {
    competitorId: companyId,
    signalType: document.getElementById('intel-clip-type').value || 'other',
    title: document.getElementById('intel-clip-title').value,
    notes: document.getElementById('intel-clip-notes').value,
    link: document.getElementById('intel-clip-link').value,
  };

  if (!payload.competitorId) {
    $status.textContent = 'Company required — select above';
    $status.style.color = '#ff5a5a';
    return;
  }
  if (!payload.title) {
    $status.textContent = 'Title required';
    $status.style.color = '#ff5a5a';
    return;
  }

  $btn.disabled = true;
  $btn.textContent = 'Saving…';

  try {
    await apiFetch('/api/clip', { method: 'POST', body: JSON.stringify(payload) });
    $status.textContent = '✅ Signal saved to Turso!';
    $status.style.color = '#45c66a';
    await chrome.storage.local.remove(STORAGE.pendingClip);
    setTimeout(() => {
      document.getElementById('intel-clip-title').value = '';
      document.getElementById('intel-clip-notes').value = '';
      document.getElementById('intel-clip-type').value = '';
      document.getElementById('intel-clip-link').value = '';
      $status.textContent = '';
      $btn.disabled = false;
      $btn.textContent = 'Save signal to Turso';
    }, 1500);
  } catch (err) {
    $status.textContent = `❌ ${err.message}`;
    $status.style.color = '#ff5a5a';
    $btn.disabled = false;
    $btn.textContent = 'Save signal to Turso';
  }
});

// ─── Settings ───
function loadSettings() {
  chrome.storage.sync.get([STORAGE.apiUrl, STORAGE.pollMin, STORAGE.notifThreshold], (data) => {
    document.getElementById('api-url').value = data[STORAGE.apiUrl] || '';
    document.getElementById('poll-min').value = data[STORAGE.pollMin] || 5;
    document.getElementById('notif-threshold').value = String(data[STORAGE.notifThreshold] ?? 80);
  });

  // AI status display
  const $aiStatus = document.getElementById('ai-status');
  const row = (label, val) => {
    const cls = val && val !== 'unavailable' ? 'ai-available' : 'ai-unavailable';
    const text = val && val !== 'unavailable' ? '✓ ' + val : '✗ unavailable';
    return `<div class="ai-row"><span>${label}</span><span class="${cls}">${text}</span></div>`;
  };
  $aiStatus.innerHTML =
    row('Summarizer', state.ai.summarizer) +
    row('Prompt API', state.ai.prompt) +
    row('Rewriter', state.ai.rewriter);
}

document.getElementById('save-btn').addEventListener('click', async () => {
  const apiUrl = document.getElementById('api-url').value.trim().replace(/\/$/, '');
  const pollMin = Math.max(1, Math.min(60, Number(document.getElementById('poll-min').value) || 5));
  const threshold = Number(document.getElementById('notif-threshold').value);
  const $status = document.getElementById('settings-status');

  await chrome.storage.sync.set({
    [STORAGE.apiUrl]: apiUrl,
    [STORAGE.pollMin]: pollMin,
    [STORAGE.notifThreshold]: threshold,
  });

  await chrome.alarms.clear('signal-poll');
  await chrome.alarms.create('signal-poll', { periodInMinutes: pollMin });

  $status.textContent = 'Saved ✓';
  setTimeout(() => { $status.textContent = ''; }, 2000);
});

