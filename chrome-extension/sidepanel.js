import { STORAGE, IMPACT_COLORS, SIGNAL_TYPES, impactBand, timeAgo } from './shared/constants.js';
import { apiFetch, getApiUrl } from './shared/api.js';
import { aiStatus, summarizeText, classifySignal, rewriteNotes, intelCheck } from './shared/ai.js';

// ─── State ───
let state = {
  companies: [],
  signals: [],
  filtered: [],
  clipData: null,
  intelData: null,  // pre-baked company intel from data/companies.json
  ai: { summarizer: 'unavailable', prompt: 'unavailable', rewriter: 'unavailable' },
};

// ─── DOM refs ───
const $errorBanner = document.getElementById('error-banner');

// ─── Tab switching ───
document.querySelectorAll('.tab').forEach(btn => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('.tab').forEach(t => t.classList.remove('active'));
    document.querySelectorAll('.tab-content').forEach(c => c.classList.remove('active'));
    btn.classList.add('active');
    document.getElementById(`tab-${btn.dataset.tab}`).classList.add('active');
    // Hide signal detail when switching tabs
    document.getElementById('signal-detail').classList.add('hidden');
  });
});

// ─── Init ───
async function init() {
  chrome.action.setBadgeText({ text: '' });

  const apiUrl = await getApiUrl();
  if (!apiUrl) {
    showSetupScreen();
    return;
  }

  state.ai = await aiStatus();
  setupAiButtons();

  // Check for pending clip data — auto-switch to Intel tab
  const clipStore = await chrome.storage.local.get(STORAGE.pendingClip);
  state.clipData = clipStore[STORAGE.pendingClip] || null;

  if (state.clipData) {
    document.querySelectorAll('.tab').forEach(t => t.classList.remove('active'));
    document.querySelectorAll('.tab-content').forEach(c => c.classList.remove('active'));
    document.querySelector('[data-tab="intel"]').classList.add('active');
    document.getElementById('tab-intel').classList.add('active');
  }

  try {
    const [configRes, signalsData, cronRes] = await Promise.all([
      apiFetch('/api/config'),
      apiFetch('/api/signals'),
      apiFetch('/api/cron-status').catch(() => null),
    ]);

    state.companies = configRes.companies || [];
    state.signals = Array.isArray(signalsData) ? signalsData : (signalsData.signals || []);
    state.filtered = state.signals;

    // Load pre-baked intel data (generated by `npm run chrome-data`)
    try {
      const intelRes = await fetch(chrome.runtime.getURL('data/companies.json'));
      if (intelRes.ok) state.intelData = await intelRes.json();
    } catch { /* no local data yet — Intel Check falls back to API signals */ }

    renderDashboard(cronRes);
    populateFilters();
    populateIntelTab();
    loadSettings();
  } catch (err) {
    showError(err.message);
  }
}

