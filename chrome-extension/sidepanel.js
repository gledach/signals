// ─── Filters ───
function populateFilters() {
  const $company = document.getElementById('filter-company');
  state.companies.forEach(c => {
    const opt = document.createElement('option');
    opt.value = c.id;
    opt.textContent = c.name || c.id;
    $company.appendChild(opt);
  });

  const $type = document.getElementById('filter-type');
  // Collect actual types from signals
  const usedTypes = [...new Set(state.signals.map(s => s.signalType).filter(Boolean))];
  usedTypes.sort();
  usedTypes.forEach(t => {
    const opt = document.createElement('option');
    opt.value = t;
    opt.textContent = t.replace(/_/g, ' ');
    $type.appendChild(opt);
  });

  // Listen for filter changes
  $company.addEventListener('change', applyFilters);
  document.getElementById('filter-band').addEventListener('change', applyFilters);
  $type.addEventListener('change', applyFilters);
}

function applyFilters() {
  const companyVal = document.getElementById('filter-company').value;
  const bandVal = document.getElementById('filter-band').value;
  const typeVal = document.getElementById('filter-type').value;

  state.filtered = state.signals.filter(s => {
    if (companyVal && s.companyId !== companyVal) return false;
    if (bandVal && (s.impactBand || 'noise') !== bandVal) return false;
    if (typeVal && s.signalType !== typeVal) return false;
    return true;
  });

  renderDashboard(null);
}

// ─── Intel tab (unified Check → Clip flow) ───
function populateIntelTab() {
  const $company = document.getElementById('intel-company');
  while ($company.options.length > 1) $company.options.remove(1);

  state.companies.filter(c => !c.isUs).forEach(c => {
    const opt = document.createElement('option');
    opt.value = c.id;
    opt.textContent = c.name || c.id;
    $company.appendChild(opt);
  });

  // Populate signal type dropdown for clip form
  const $type = document.getElementById('intel-clip-type');
  SIGNAL_TYPES.forEach(t => {
    const opt = document.createElement('option');
    opt.value = t;
    opt.textContent = t.replace(/_/g, ' ');
    $type.appendChild(opt);
  });

  // Auto-fill page info from current tab
  chrome.tabs.query({ active: true, currentWindow: true }).then(([tab]) => {
    if (tab) {
      document.getElementById('intel-page-title').textContent = tab.title || '—';
      document.getElementById('intel-page-url').textContent = tab.url || '—';
      document.getElementById('intel-clip-link').value = tab.url || '';
      state.currentTab = tab;
    }
  });

  // Enable check button when company selected
  $company.addEventListener('change', () => {
    document.getElementById('btn-intel-check').disabled = !$company.value;
  });

  // If pending clip data, auto-select company + run check
  if (state.clipData) {
    autoFillFromClipData();
  }
}

async function autoFillFromClipData() {
  if (state.ai.prompt === 'unavailable' || !state.clipData) return;

  const textToClassify = state.clipData.pageText || state.clipData.selectedText || state.clipData.title || '';
  if (!textToClassify) return;

  try {
    const result = await classifySignal(textToClassify, state.companies, SIGNAL_TYPES);
    if (result && result.companyId !== 'unknown') {
      document.getElementById('intel-company').value = result.companyId;
      document.getElementById('btn-intel-check').disabled = false;
      // Auto-trigger the check
      document.getElementById('btn-intel-check').click();
    }
  } catch {}
}

// ─── AI buttons ───
function setupAiButtons() {
  if (state.ai.summarizer !== 'unavailable') {
    document.getElementById('btn-summarize-page').classList.remove('hidden');
  }
  if (state.ai.rewriter !== 'unavailable') {
    document.getElementById('btn-rewrite').classList.remove('hidden');
  }
}

// Summarize page → fill notes
document.getElementById('btn-summarize-page').addEventListener('click', async () => {
  const btn = document.getElementById('btn-summarize-page');
  btn.textContent = '⏳ Summarizing…';
  btn.disabled = true;

  try {
    const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (!tab) return;

    const response = await chrome.tabs.sendMessage(tab.id, { type: 'GET_PAGE_TEXT' });
    if (response?.pageText) {
      const summary = await summarizeText(response.pageText);
      if (summary) {
        document.getElementById('intel-clip-notes').value = summary;
      }
    }
  } catch {}
  finally {
    btn.textContent = '✨ Summarize';
    btn.disabled = false;
  }
});

