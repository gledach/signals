// ─── Intel Check (Step 1) ───
document.getElementById('btn-intel-check').addEventListener('click', async () => {
  const companyId = document.getElementById('intel-company').value;
  if (!companyId) return;

  const $btn = document.getElementById('btn-intel-check');
  const $status = document.getElementById('intel-check-status');
  const $result = document.getElementById('intel-result');
  const $clipSection = document.getElementById('intel-step-clip');

  $btn.disabled = true;
  $btn.textContent = '⏳ Analyzing…';
  $status.textContent = '';
  $result.classList.add('hidden');
  $clipSection.classList.add('hidden');

  try {
    // 1. Get page text from content script
    const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (!tab) throw new Error('No active tab');

    let pageText = '';
    try {
      const response = await chrome.tabs.sendMessage(tab.id, { type: 'GET_PAGE_TEXT' });
      pageText = response?.pageText || '';
    } catch {
      pageText = tab.title || '';
    }

    if (!pageText || pageText.length < 20) {
      $status.textContent = 'Not enough page content to analyze';
      $status.style.color = '#ff9a4d';
      return;
    }

    // 2. Get company intel — prefer local pre-baked data, fall back to API signals
    const company = state.companies.find(c => c.id === companyId);
    const companyName = company?.name || companyId;
    const localIntel = state.intelData?.companies?.[companyId];
    let signalsOrDigest;
    let signalCount;

    if (localIntel?.digest?.length) {
      signalsOrDigest = localIntel.digest;
      signalCount = localIntel.signalCount;
      const age = state.intelData.generated
        ? Math.round((Date.now() - new Date(state.intelData.generated).getTime()) / 86400_000)
        : '?';
      $status.textContent = `Comparing against ${signalCount} signals for ${companyName} (local snapshot, ${age}d old)…`;
    } else {
      signalsOrDigest = state.signals.filter(s => s.companyId === companyId);
      signalCount = signalsOrDigest.length;
      $status.textContent = `Comparing against ${signalCount} signals for ${companyName} (live API)…`;
    }
    $status.style.color = '#6b7484';

    // 3. Run AI comparison
    const analysis = await intelCheck(pageText, companyName, signalsOrDigest);

    if (!analysis) {
      $status.textContent = 'Prompt API unavailable — enable Chrome AI flags';
      $status.style.color = '#ff5a5a';
      return;
    }

    // 4. Show analysis result
    $status.textContent = '';
    $result.classList.remove('hidden');
    document.getElementById('intel-analysis').textContent = analysis;

    // 5. Show clip form (pre-filled)
    $clipSection.classList.remove('hidden');
    document.getElementById('intel-clip-title').value = tab.title || '';

    // Try to auto-detect signal type
    if (state.ai.prompt !== 'unavailable') {
      try {
        const classification = await classifySignal(pageText, state.companies, SIGNAL_TYPES);
        if (classification && classification.signalType) {
          document.getElementById('intel-clip-type').value = classification.signalType;
          const $banner = document.getElementById('intel-ai-banner');
          const $bannerText = document.getElementById('intel-ai-text');
          $banner.classList.remove('hidden');
          $bannerText.textContent = `🤖 Detected: ${classification.signalType} (${classification.confidence}%)`;
        }
      } catch {}
    }

    // Pre-fill notes with a condensed version of the analysis
    if (state.ai.summarizer !== 'unavailable') {
      const summary = await summarizeText(pageText);
      if (summary) document.getElementById('intel-clip-notes').value = summary;
    }

  } catch (err) {
    $status.textContent = `❌ ${err.message}`;
    $status.style.color = '#ff5a5a';
  } finally {
    $btn.disabled = !document.getElementById('intel-company').value;
    $btn.textContent = 'Check page against intel';
  }
});

